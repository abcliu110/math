/* 排除表题（2.14b 推理，problems/deduce.js）的参考解：每一步是 [人, 格]，人 0 小明、1 小红、2 小刚；
 * 格 0–2 是颜色（红、蓝、绿），3–5 是宠物（猫、狗、兔）。必须能让该题通关（满足 goal）。 */
'use strict';
module.exports = {
  'deduce-who'(h) {
    const b = h.role('排除表');
    h.deduce(b, [
      [2, 1], [1, 1], [1, 2],   // 小刚不是蓝；小红不是蓝、不是绿
      [1, 0],                   // 小红只剩红：是
      [2, 2],                   // 小刚的颜色只剩绿：是
      [0, 1],                   // 小明的颜色只剩蓝：是
      [1, 3], [2, 3],           // 养猫的人穿蓝色：小红、小刚都不养猫
      [0, 3],                   // 小明养猫：是
      [1, 4],                   // 小红不养狗
      [1, 5],                   // 小红养兔：是
      [2, 4],                   // 小刚养狗：是
    ]);
  },
};
