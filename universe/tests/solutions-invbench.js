/* “不变量放大镜”题的参考解（problems/invbench.js）。hist 是每一步的局面，lens 放大镜看第几个量、view 怎么看，ans 下的结论，
 * book 研究本，pick 追问选了第几个。阶梯题一层一层做（里程碑做到就记下）。 */
'use strict';
const at = (h, x) => { Object.keys(x).forEach((k) => h.set(h.role('iv'), k, x[k])); };
const S1 = '1,2,3,4,5,6|3,3,4,5,6|6,4,5,6|10,5,6|15,6|21', S2 = '1,2,3,4,5,6|1,2,3,4,11|1,2,3,15|1,2,18|1,20|21';
